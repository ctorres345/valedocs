// Regenerates src/storage/logos-default.ts from assets/logos/left.png and right.png.
// Usage: npm run logos   (after changing the images). A missing image bundles no logo on that side (null).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

function logo(file) {
  const path = new URL(`../assets/logos/${file}`, import.meta.url);
  if (!existsSync(path)) return 'null';
  const png = readFileSync(path);
  // Image size: width and height live in the PNG IHDR header
  const width = png.readUInt32BE(16);
  const height = png.readUInt32BE(20);
  return `{ uri: 'data:image/png;base64,${png.toString('base64')}', width: ${width}, height: ${height} }`;
}

const output = `// GENERATED by scripts/embed-logos.mjs from assets/logos. Do not edit by hand.
import type { Logo } from './logos';

export const DEFAULT_LEFT_LOGO: Logo | null = ${logo('left.png')};
export const DEFAULT_RIGHT_LOGO: Logo | null = ${logo('right.png')};
`;
writeFileSync(new URL('../src/storage/logos-default.ts', import.meta.url), output);
console.log('src/storage/logos-default.ts updated');
